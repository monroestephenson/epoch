package dev.epoch

import dev.epoch.core.*
import dev.epoch.postgres.PostgresVerifier
import org.junit.jupiter.api.Assertions.*
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.nio.file.Path
import kotlin.io.path.createDirectories
import kotlin.io.path.writeText

/** Catalog identity and PostgreSQL write capabilities determine which compatibility views are proven. */
class CompatibilityViewsTest {
    @TempDir lateinit var directory: Path

    private fun verify(baselineSql: String, queries: List<QueryContract>, migrationSql: String,
        expectedBaselineVerdict: Verdict = Verdict.SAFE): CompatibilityReport {
        val baseline = directory.resolve("baseline").createDirectories()
        baseline.resolve("V1__baseline.sql").writeText(baselineSql)
        val pending = directory.resolve("pending").createDirectories()
        pending.resolve("V2__compatibility_view.sql").writeText(migrationSql)
        val contract = DatabaseContract(applicationVersion = "compatibility-view-regressions", queries = queries,
            coverage = Coverage(complete = true, mechanisms = listOf("Explicit finite SQL fixture contract")))
        return PostgresVerifier().verify(contract, baseline, pending).also {
            val health = requireNotNull(it.baseline)
            assertEquals(expectedBaselineVerdict, health.verdict, it.toString())
            assertTrue(health.findings.none { finding -> finding.ruleId == "BASELINE_SQL_UNVERIFIED" ||
                finding.ruleId.startsWith("INVALID_BASELINE_") }, it.toString())
        }
    }

    private fun crud(name: String, sqlName: String = name, payload: String = "label", payloadType: String = "text",
        writePayload: Boolean = true): List<QueryContract> {
        val table = if ('.' in name) name else "public.$name"
        val id = ColumnReference(table, "id")
        val value = ColumnReference(table, payload)
        val supplied = if (writePayload) listOf(id, value) else listOf(id)
        val inserted = if (writePayload) "id, $payload" else "id"
        val parameters = if (writePayload) listOf("bigint", payloadType) else listOf("bigint")
        val updated = if (writePayload) value else id
        return listOf(
            QueryContract("$name.read", Operation.SELECT, "SELECT id, $payload FROM $sqlName WHERE id = ?",
                tables = listOf(table), columns = listOf(id, value), parameterTypes = listOf("bigint"), dependenciesComplete = true),
            QueryContract("$name.insert", Operation.INSERT,
                "INSERT INTO $sqlName ($inserted) VALUES (${parameters.joinToString { "?" }})",
                tables = listOf(table), columns = supplied, writeColumns = supplied,
                parameterTypes = parameters, dependenciesComplete = true, targetTable = table),
            QueryContract("$name.update", Operation.UPDATE, "UPDATE $sqlName SET ${updated.column} = ? WHERE id = ?",
                tables = listOf(table), columns = listOf(id, updated).distinct(), writeColumns = listOf(updated),
                parameterTypes = listOf(if (writePayload) payloadType else "bigint", "bigint"),
                dependenciesComplete = true, targetTable = table),
            QueryContract("$name.delete", Operation.DELETE, "DELETE FROM $sqlName WHERE id = ?",
                tables = listOf(table), columns = listOf(id), parameterTypes = listOf("bigint"),
                dependenciesComplete = true, targetTable = table),
        )
    }

    @Test fun `pure DDL compatibility views preserve each integer identity type and constant default`() {
        val tables = listOf("small_accounts" to "smallint", "integer_accounts" to "integer", "accounts" to "bigint")
        val queries = tables.flatMap { (name, type) ->
            crud(name).map { query ->
                when (query.operation) {
                    Operation.SELECT -> query.copy(resultColumns = listOf(ResultColumn("id", type), ResultColumn("label", "text")))
                    Operation.INSERT -> query.copy(
                        sql = "INSERT INTO $name (label) VALUES (?)",
                        columns = listOf(ColumnReference("public.$name", "label")),
                        writeColumns = listOf(ColumnReference("public.$name", "label")), parameterTypes = listOf("text"),
                    )
                    else -> query
                }
            }
        }
        val baseline = tables.joinToString("\n") { (name, type) ->
            "CREATE TABLE $name (id $type GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "label text, region text NOT NULL DEFAULT 'legacy');"
        }
        val migrations = tables.joinToString("\n") { (name, _) ->
            "ALTER TABLE $name RENAME TO ${name}_v2; CREATE VIEW $name AS SELECT * FROM ${name}_v2;"
        }
        val report = verify(baseline, queries, migrations)
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
        assertEquals(tables.map { "public.${it.first}" }.toSet(), report.migrations.single().findings
            .filter { it.ruleId == "TRANSPARENT_COMPATIBILITY_VIEW" }.map { it.objectName }.toSet(), report.toString())
    }

    @Test fun `transparent rename preserves self-referential and incoming FK action dependencies`() {
        val report = verify("""
            CREATE TABLE accounts (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                label text,
                parent_id bigint REFERENCES accounts(id) ON DELETE CASCADE ON UPDATE CASCADE
            );
            CREATE TABLE orders (
                id bigint PRIMARY KEY,
                account_id bigint REFERENCES accounts(id) ON DELETE SET NULL ON UPDATE CASCADE
            );
        """.trimIndent(), crud("accounts") + crud("orders", payload = "account_id", payloadType = "bigint"), """
            ALTER TABLE accounts RENAME TO accounts_v2;
            CREATE VIEW accounts AS SELECT * FROM accounts_v2;
        """.trimIndent())

        assertEquals(Verdict.SAFE, report.verdict, report.toString())
        val findings = report.migrations.single().findings
        assertTrue(findings.any { it.ruleId == "TRANSPARENT_COMPATIBILITY_VIEW" && it.objectName == "public.accounts" }, report.toString())
        assertTrue(findings.none { it.ruleId == "DATABASE_BEHAVIOR_CHANGED" ||
            it.ruleId == "INDIRECT_WRITE_DEPENDENCY_UNPROVEN" }, report.toString())
    }

    @Test fun `grouped view proves all old write operations unsupported`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label text);", crud("accounts"), """
            ALTER TABLE accounts RENAME TO accounts_v2;
            CREATE VIEW accounts AS SELECT id, label FROM accounts_v2 GROUP BY id, label;
        """.trimIndent())
        assertEquals(Verdict.BREAKING, report.verdict, report.toString())
        val unsupported = report.migrations.single().findings.filter { it.ruleId == "VIEW_WRITE_UNSUPPORTED" }
        assertTrue(unsupported.isNotEmpty(), report.toString())
        assertTrue(unsupported.all { it.verdict == Verdict.BREAKING }, report.toString())
        assertEquals(setOf("accounts.insert", "accounts.update", "accounts.delete"),
            unsupported.flatMap { it.affectedContractIds }.toSet(), report.toString())
        assertTrue(report.migrations.single().findings.none { it.ruleId == "REFERENCED_TABLE_DROPPED" }, report.toString())
    }

    @Test fun `filtered computed security trigger privilege owner and collation views remain unproven`() {
        val names = listOf("filtered", "computed", "barrier", "invoker", "triggered", "granted", "reowned", "collated")
        val baseline = names.joinToString("\n") {
            val labelType = if (it == "collated") "varchar(255)" else "text"
            "CREATE TABLE $it (id bigint PRIMARY KEY, label $labelType);"
        } + """
            CREATE TABLE collation_only (id bigint PRIMARY KEY, label varchar(255));
            CREATE FUNCTION preserve_view_row() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN RETURN NEW; END;
            $$;
            CREATE TRIGGER preserve_row BEFORE INSERT OR UPDATE ON triggered
                FOR EACH ROW EXECUTE FUNCTION preserve_view_row();
            GRANT SELECT ON granted TO PUBLIC;
            CREATE ROLE compatibility_view_owner;
        """.trimIndent()
        val migrations = names.joinToString("\n") { name ->
            val projection = when (name) {
                "filtered" -> "SELECT * FROM ${name}_v2 WHERE id > 0"
                "computed" -> "SELECT id, coalesce(label, '') AS label FROM ${name}_v2"
                else -> "SELECT * FROM ${name}_v2"
            }
            val options = when (name) {
                "barrier" -> "WITH (security_barrier = true)"
                "invoker" -> "WITH (security_invoker = true)"
                else -> ""
            }
            val collationChange = if (name == "collated")
                "ALTER TABLE collated_v2 ALTER COLUMN label TYPE varchar(255) COLLATE \"C\";" else ""
            "ALTER TABLE $name RENAME TO ${name}_v2; $collationChange CREATE VIEW $name $options AS $projection;" +
                if (name == "reowned") " ALTER TABLE reowned_v2 OWNER TO compatibility_view_owner;" else ""
        } + "\nALTER TABLE collation_only ALTER COLUMN label TYPE varchar(255) COLLATE \"C\";"
        // Computed output remains readable; its old writers touch only the direct id column.
        val queries = names.flatMap { crud(it, writePayload = it != "computed") } + crud("collation_only")
        val report = verify(baseline, queries, migrations, expectedBaselineVerdict = Verdict.UNKNOWN)
        assertEquals(Verdict.UNKNOWN, report.verdict, report.toString())
        val findings = report.migrations.single().findings
        names.forEach { name ->
            assertTrue(findings.any { it.ruleId == "RELATION_KIND_CHANGED" && it.objectName == "public.$name" &&
                it.verdict == Verdict.UNKNOWN && "$name.insert" in it.affectedContractIds }, "$name: $report")
        }
        assertTrue(findings.any { it.ruleId == "COLUMN_COLLATION_CHANGED" &&
            it.objectName == "public.collation_only.label" && it.verdict == Verdict.UNKNOWN &&
            "collation_only.read" in it.affectedContractIds }, report.toString())
        assertTrue(findings.none { it.verdict == Verdict.BREAKING }, report.toString())
        assertTrue(findings.none { it.ruleId == "TRANSPARENT_COMPATIBILITY_VIEW" }, report.toString())
    }

    @Test fun `matching backing table shape cannot replace original relation identity`() {
        val report = verify("CREATE TABLE accounts (id bigint, label text);", crud("accounts"), """
            ALTER TABLE accounts RENAME TO accounts_original;
            CREATE TABLE accounts_v2 (LIKE accounts_original INCLUDING ALL);
            CREATE VIEW accounts AS SELECT * FROM accounts_v2;
        """.trimIndent())
        assertEquals(Verdict.UNKNOWN, report.verdict, report.toString())
        assertTrue(report.migrations.single().findings.any {
            it.ruleId == "RELATION_KIND_CHANGED" && it.objectName == "public.accounts"
        }, report.toString())
        assertTrue(report.migrations.single().findings.none { it.ruleId == "TRANSPARENT_COMPATIBILITY_VIEW" }, report.toString())
    }

    @Test fun `renamed backing table preserves incoming self foreign keys indexes and sequence ownership`() {
        val report = verify("""
            CREATE TABLE accounts (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label text,
                parent_id bigint REFERENCES accounts(id));
            CREATE INDEX accounts_label_lookup ON accounts(label);
            CREATE TABLE orders (id bigint PRIMARY KEY, account_id bigint REFERENCES accounts(id));
            CREATE INDEX orders_account_lookup ON orders(account_id);
        """.trimIndent(), crud("accounts") + crud("orders", payload = "account_id", payloadType = "bigint"), """
            ALTER TABLE accounts RENAME TO accounts_v2;
            CREATE VIEW accounts AS SELECT * FROM accounts_v2;
        """.trimIndent())
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
        assertTrue(report.migrations.single().findings.any { it.ruleId == "TRANSPARENT_COMPATIBILITY_VIEW" }, report.toString())
    }

    @Test fun `quoted schema and table identifiers retain transparent compatibility proof`() {
        val report = verify("""
            CREATE SCHEMA "Legacy Schema";
            CREATE TABLE "Legacy Schema"."Account Table" (id bigint PRIMARY KEY, label text);
        """.trimIndent(), crud("Legacy Schema.Account Table", "\"Legacy Schema\".\"Account Table\""), """
            ALTER TABLE "Legacy Schema"."Account Table" RENAME TO "Current Table";
            CREATE VIEW "Legacy Schema"."Account Table" AS SELECT * FROM "Legacy Schema"."Current Table";
        """.trimIndent())
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
        assertTrue(report.migrations.single().findings.any { it.ruleId == "TRANSPARENT_COMPATIBILITY_VIEW" }, report.toString())
    }
}
