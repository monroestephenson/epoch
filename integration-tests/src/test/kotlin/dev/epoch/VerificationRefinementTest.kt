package dev.epoch

import dev.epoch.core.*
import dev.epoch.postgres.PostgresVerifier
import org.junit.jupiter.api.Assertions.*
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.nio.file.Path
import kotlin.io.path.createDirectories
import kotlin.io.path.writeText

/** Regression cases use actual PostgreSQL catalogs and SQL planning, including implicit DDL effects. */
class VerificationRefinementTest {
    @TempDir lateinit var directory: Path

    private fun verify(baselineSql: String, contract: DatabaseContract, vararg changes: String): CompatibilityReport {
        val baseline = directory.resolve("baseline").createDirectories()
        baseline.resolve("V1__baseline.sql").writeText(baselineSql)
        val pending = directory.resolve("pending").createDirectories()
        changes.forEachIndexed { index, sql -> pending.resolve("V${index + 2}__change.sql").writeText(sql) }
        return PostgresVerifier().verify(contract, baseline, pending)
    }

    private fun contract(vararg queries: QueryContract, entities: List<EntityContract> = emptyList()) = DatabaseContract(
        applicationVersion = "verification-refinements", entities = entities, queries = queries.toList(),
        coverage = Coverage(complete = true, mechanisms = listOf("Explicit finite SQL fixture contract")),
    )

    private fun read(vararg columns: String) = QueryContract(
        "Account.read", Operation.SELECT, "SELECT ${columns.joinToString()} FROM accounts",
        tables = listOf("public.accounts"), columns = columns.map { ColumnReference("public.accounts", it) },
        dependenciesComplete = true,
    )

    private fun insert(type: String = "text", column: String = "label") = QueryContract(
        "Account.insert", Operation.INSERT, "INSERT INTO accounts (id, $column) VALUES (?, ?)",
        tables = listOf("public.accounts"),
        columns = listOf("id", column).map { ColumnReference("public.accounts", it) },
        writeColumns = listOf("id", column).map { ColumnReference("public.accounts", it) },
        parameterTypes = listOf("bigint", type), dependenciesComplete = true, targetTable = "public.accounts",
    )

    private fun mapped(column: ColumnContract, operations: Set<Operation> = setOf(Operation.INSERT)) = EntityContract(
        "Account", "public.accounts", listOf(ColumnContract("id", "bigint", nullable = false), column), operations,
    )

    @Test fun `compatibility view does not fabricate a missing-table breaking finding`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label text);",
            contract(read("id", "label"), insert()),
            "ALTER TABLE accounts RENAME TO accounts_v2; CREATE VIEW accounts AS SELECT id, label FROM accounts_v2;",
        )
        assertEquals(Verdict.UNKNOWN, report.verdict, report.toString())
        assertFalse(report.migrations.flatMap { it.findings }.any { it.verdict == Verdict.BREAKING }, report.toString())
        assertFalse(report.migrations.flatMap { it.findings }.any { it.ruleId == "POSTGRES_SQL_REJECTED" }, report.toString())
    }

    @Test fun `updatable compatibility view inherits backing identity and defaults for old omitted-column INSERT`() {
        val oldInsert = QueryContract("Account.insert", Operation.INSERT, "INSERT INTO accounts (label) VALUES (?)",
            tables = listOf("public.accounts"), columns = listOf(ColumnReference("public.accounts", "label")),
            writeColumns = listOf(ColumnReference("public.accounts", "label")), parameterTypes = listOf("text"),
            dependenciesComplete = true, targetTable = "public.accounts")
        val report = verify("""
            CREATE TABLE accounts (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                label text, region text NOT NULL DEFAULT 'legacy');
        """.trimIndent(), contract(read("id", "label"), oldInsert), """
            ALTER TABLE accounts RENAME TO accounts_v2;
            CREATE VIEW accounts AS SELECT id, label, region FROM accounts_v2;
            INSERT INTO accounts (label) VALUES ('actual-old-insert');
            DELETE FROM accounts WHERE label = 'actual-old-insert';
        """.trimIndent())
        // PostgreSQL actually executes the old INSERT above. View catalog columns
        // do not expose the backing identity/default even though writes use them.
        assertEquals(Verdict.UNKNOWN, report.verdict, report.toString())
        assertTrue(report.migrations.flatMap { it.findings }.none { it.verdict == Verdict.BREAKING }, report.toString())
        assertTrue(report.migrations.flatMap { it.findings }.none { it.ruleId == "POSTGRES_SQL_REJECTED" }, report.toString())
    }

    @Test fun `dropping unrelated table also drops its owned sequence and FK without poisoning the contract`() {
        val report = verify("""
            CREATE TABLE accounts (id bigint PRIMARY KEY);
            CREATE TABLE audit_log (id bigserial PRIMARY KEY, account_id bigint REFERENCES accounts(id));
        """.trimIndent(), contract(read("id")), "DROP TABLE audit_log;")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
        assertFalse(report.migrations.flatMap { it.findings }.any { it.ruleId == "SEQUENCE_CHANGED" }, report.toString())
    }

    @Test fun `dropping unrelated serial column removes owned sequence and index safely`() {
        val report = verify("""
            CREATE TABLE accounts (id bigint PRIMARY KEY, unused bigserial);
            CREATE INDEX accounts_unused ON accounts(unused);
        """.trimIndent(), contract(read("id")), "ALTER TABLE accounts DROP COLUMN unused;")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
    }

    @Test fun `new table own identity sequence has no old contract dependency`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY);", contract(read("id")),
            "CREATE TABLE archive (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
        assertFalse(report.migrations.flatMap { it.findings }.any { it.ruleId == "SEQUENCE_CHANGED" }, report.toString())
    }

    @Test fun `added required column with constant default preserves omitted-column inserts`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label text);", contract(insert()),
            "ALTER TABLE accounts ADD COLUMN region text NOT NULL DEFAULT 'unknown';")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
        assertTrue(report.migrations.flatMap { it.findings }.any { it.ruleId == "CONSTANT_DEFAULT_COLUMN_ADDED" }, report.toString())
    }

    @Test fun `volatile default is not equated with a literal default`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label text);", contract(insert()),
            "ALTER TABLE accounts ADD COLUMN token double precision NOT NULL DEFAULT random();")
        assertEquals(Verdict.UNKNOWN, report.verdict, report.toString())
    }

    @Test fun `plain nonunique index creation and removal both preserve structural contract`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label varchar(20));", contract(read("id", "label"), insert()),
            "CREATE INDEX accounts_label_lookup ON accounts(label);", "DROP INDEX accounts_label_lookup;")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
        assertTrue(report.migrations.all { it.verdict == Verdict.SAFE }, report.toString())
    }

    @Test fun `unique index addition remains unknown without accepted input proof`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label text);", contract(insert()),
            "CREATE UNIQUE INDEX accounts_unique_label ON accounts(label);")
        assertEquals(Verdict.UNKNOWN, report.verdict, report.toString())
    }

    @Test fun `dropping baseline unique index without ON CONFLICT does not restrict old writes`() {
        val report = verify("""
            CREATE TABLE accounts (id bigint PRIMARY KEY, label text);
            CREATE UNIQUE INDEX accounts_unique_label ON accounts(label);
        """.trimIndent(), contract(insert()), "DROP INDEX accounts_unique_label;")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
    }

    @Test fun `dropping unique index required by ON CONFLICT is rejected by PostgreSQL`() {
        val upsert = insert().copy(sql = "INSERT INTO accounts (id, label) VALUES (?, ?) ON CONFLICT(label) DO NOTHING")
        val report = verify("""
            CREATE TABLE accounts (id bigint PRIMARY KEY, label text);
            CREATE UNIQUE INDEX accounts_unique_label ON accounts(label);
        """.trimIndent(), contract(upsert), "DROP INDEX accounts_unique_label;")
        assertNotEquals(Verdict.SAFE, report.verdict, report.toString())
        assertTrue(report.migrations.flatMap { it.findings }.any { it.ruleId == "POSTGRES_SQL_REJECTED" }, report.toString())
    }

    @Test fun `new FK referencing read-only target cannot restrict a declared write`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY);", contract(read("id")),
            "CREATE TABLE audit_log (id bigint PRIMARY KEY, account_id bigint REFERENCES accounts(id));")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
    }

    @Test fun `new FK identifies old DELETE on referenced table precisely`() {
        val delete = QueryContract("Account.delete", Operation.DELETE, "DELETE FROM accounts WHERE id = ?",
            tables = listOf("public.accounts"), columns = listOf(ColumnReference("public.accounts", "id")),
            parameterTypes = listOf("bigint"), dependenciesComplete = true, targetTable = "public.accounts")
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY);", contract(read("id"), delete),
            "CREATE TABLE audit_log (id bigint PRIMARY KEY, account_id bigint REFERENCES accounts(id));")
        assertEquals(Verdict.UNKNOWN, report.verdict, report.toString())
        val finding = report.migrations.flatMap { it.findings }.single { it.ruleId == "NEW_REFERENTIAL_CONSTRAINT" }
        assertEquals(listOf("Account.delete"), finding.affectedContractIds)
    }

    @Test fun `new FK does not affect UPDATE of an unrelated referenced-table column`() {
        val update = QueryContract("Account.update", Operation.UPDATE, "UPDATE accounts SET label = ? WHERE id = ?",
            tables = listOf("public.accounts"), columns = listOf("id", "label").map { ColumnReference("public.accounts", it) },
            writeColumns = listOf(ColumnReference("public.accounts", "label")), parameterTypes = listOf("text", "bigint"),
            dependenciesComplete = true, targetTable = "public.accounts")
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label text);", contract(update),
            "CREATE TABLE audit_log (id bigint PRIMARY KEY, account_id bigint REFERENCES accounts(id));")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
    }

    @Test fun `SET NOT NULL excludes mapped nullable write input`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label text);",
            contract(insert(), entities = listOf(mapped(ColumnContract("label", "text", nullable = true)))),
            "ALTER TABLE accounts ALTER COLUMN label SET NOT NULL;")
        assertEquals(Verdict.BREAKING, report.verdict, report.toString())
        assertTrue(report.migrations.flatMap { it.findings }.any { it.ruleId == "MAPPED_NULL_REJECTED" }, report.toString())
    }

    @Test fun `varchar narrowing excludes old mapped maximum length`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label varchar(20));",
            contract(insert(), entities = listOf(mapped(ColumnContract("label", "varchar", length = 20)))),
            "ALTER TABLE accounts ALTER COLUMN label TYPE varchar(10);")
        assertEquals(Verdict.BREAKING, report.verdict, report.toString())
        assertTrue(report.migrations.flatMap { it.findings }.any { it.ruleId == "MAPPED_TYPE_NARROWED" }, report.toString())
    }

    @Test fun `integer widening is safe for a write-only contract`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, amount integer);",
            contract(insert("integer", "amount"), entities = listOf(mapped(ColumnContract("amount", "integer")))),
            "ALTER TABLE accounts ALTER COLUMN amount TYPE bigint;")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
    }

    @Test fun `integer widening still checks old result hydration`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, amount integer);", contract(read("id", "amount")),
            "ALTER TABLE accounts ALTER COLUMN amount TYPE bigint;")
        assertNotEquals(Verdict.SAFE, report.verdict, report.toString())
        assertTrue(report.migrations.flatMap { it.findings }.any { it.ruleId == "RESULT_SIGNATURE_CHANGED" }, report.toString())
    }

    @Test fun `varchar widening preserves declared write domain`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label varchar(20));",
            contract(insert(), entities = listOf(mapped(ColumnContract("label", "varchar", length = 20)))),
            "ALTER TABLE accounts ALTER COLUMN label TYPE varchar(40);")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
    }

    @Test fun `numeric precision narrowing excludes values within mapped precision and scale`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, amount numeric(8,2));",
            contract(insert("numeric", "amount"), entities = listOf(mapped(ColumnContract("amount", "numeric", precision = 8, scale = 2)))),
            "ALTER TABLE accounts ALTER COLUMN amount TYPE numeric(6,2);")
        assertEquals(Verdict.BREAKING, report.verdict, report.toString())
        assertTrue(report.migrations.flatMap { it.findings }.any { it.ruleId == "MAPPED_TYPE_NARROWED" }, report.toString())
    }

    @Test fun `increased numeric integer and fractional precision preserves write domain`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, amount numeric(8,2));",
            contract(insert("numeric", "amount"), entities = listOf(mapped(ColumnContract("amount", "numeric", precision = 8, scale = 2)))),
            "ALTER TABLE accounts ALTER COLUMN amount TYPE numeric(12,4);")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
    }

    @Test fun `enum check excluding an old mapped value is breaking`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label text);",
            contract(insert(), entities = listOf(mapped(ColumnContract("label", "text", enumValues = listOf("OPEN", "CLOSED"))))),
            "ALTER TABLE accounts ADD CONSTRAINT account_status CHECK (label IN ('OPEN'));")
        assertEquals(Verdict.BREAKING, report.verdict, report.toString())
        assertTrue(report.migrations.flatMap { it.findings }.any { it.ruleId == "ENUM_VALUE_REJECTED" }, report.toString())
    }

    @Test fun `dropping default required by omitted nonnull insert column is breaking`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label text, region text NOT NULL DEFAULT 'unknown');",
            contract(insert()), "ALTER TABLE accounts ALTER COLUMN region DROP DEFAULT;")
        assertEquals(Verdict.BREAKING, report.verdict, report.toString())
    }

    @Test fun `dropping identity required by generated identifier insert is breaking`() {
        val insert = QueryContract("Account.insert", Operation.INSERT, "INSERT INTO accounts (label) VALUES (?)",
            tables = listOf("public.accounts"), columns = listOf(ColumnReference("public.accounts", "label")),
            writeColumns = listOf(ColumnReference("public.accounts", "label")), parameterTypes = listOf("text"),
            dependenciesComplete = true, targetTable = "public.accounts")
        val report = verify("CREATE TABLE accounts (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label text);",
            contract(insert), "ALTER TABLE accounts ALTER COLUMN id DROP IDENTITY;")
        assertEquals(Verdict.BREAKING, report.verdict, report.toString())
    }

    @Test fun `no-op nullability ALTER creates no false compatibility concern`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label text NOT NULL);", contract(insert()),
            "ALTER TABLE accounts ALTER COLUMN label SET NOT NULL;")
        assertEquals(Verdict.SAFE, report.verdict, report.toString())
        assertTrue(report.migrations.flatMap { it.findings }.none { it.ruleId == "UNSUPPORTED_MIGRATION_EFFECT" }, report.toString())
    }

    @Test fun `same-type COLLATE alteration is not treated as a no-op`() {
        val report = verify("CREATE TABLE accounts (id bigint PRIMARY KEY, label text);",
            contract(read("id", "label")), "ALTER TABLE accounts ALTER COLUMN label TYPE text COLLATE \"C\";")
        assertEquals(Verdict.UNKNOWN, report.verdict, report.toString())
        assertTrue(report.migrations.flatMap { it.findings }.any { it.ruleId == "UNSUPPORTED_MIGRATION_EFFECT" }, report.toString())
    }

    @Test fun `query plans are reused only for unchanged dependencies and cached failures remain visible`() {
        val audit = QueryContract("Audit.read", Operation.SELECT, "SELECT id FROM audit_log",
            tables = listOf("public.audit_log"), columns = listOf(ColumnReference("public.audit_log", "id")),
            dependenciesComplete = true)
        val report = verify("""
            CREATE TABLE accounts (id bigint PRIMARY KEY, label varchar(20));
            CREATE TABLE audit_log (id bigint PRIMARY KEY);
        """.trimIndent(), contract(read("id", "label"), audit),
            "ALTER TABLE accounts ALTER COLUMN label TYPE varchar(40);",
            "ALTER TABLE audit_log ADD COLUMN metadata text;",
            "ALTER TABLE accounts DROP COLUMN label;",
            "ALTER TABLE audit_log ADD COLUMN detail text;",
        )
        assertEquals(listOf(1, 0, 1, 0), report.migrations.map { it.replannedQueries }, report.toString())
        assertEquals(listOf(1, 2, 1, 2), report.migrations.map { it.reusedQueries }, report.toString())
        assertEquals(Verdict.BREAKING, report.migrations[2].verdict, report.toString())
        assertEquals(Verdict.BREAKING, report.migrations[3].verdict, report.toString())
        assertTrue(report.migrations[3].findings.any {
            it.ruleId == "POSTGRES_SQL_REJECTED" && it.affectedContractIds == listOf("Account.read")
        }, report.toString())
    }
}
